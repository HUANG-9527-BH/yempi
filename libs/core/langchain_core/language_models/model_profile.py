"""模型配置文件类型与工具函数。"""

import logging
import warnings
from typing import get_type_hints

from pydantic import ConfigDict
from typing_extensions import TypedDict

logger = logging.getLogger(__name__)


class ModelProfile(TypedDict, total=False):
    """聊天模型功能的描述，通过 `model.profile` 暴露。

    See the
    [model profiles guide](https://docs.langchain.com/oss/python/langchain/models#model-profiles)
    for concepts and usage. Data is sourced from
    [models.dev](https://github.com/sst/models.dev), augmented with additional
    fields, and generated by the
    [`langchain-model-profiles`](https://github.com/langchain-ai/langchain/tree/master/libs/model-profiles)
    package (via its `langchain-profiles` CLI).

    !!! warning "测试版功能"

        字段和格式可能发生变化。这是一个 `total=False`
        `TypedDict`，因此任何字段都可能缺失——访问时请使用 `.get()` 进行保护。
    """

    __pydantic_config__ = ConfigDict(extra="allow")  # type: ignore[misc]

        # --- 模型元数据 ---

    name: str
    """人类可读的模型名称（例如 `'GPT-5'`）。"""

    status: str
    """模型生命周期状态（例如 `'active'`、`'deprecated'`）。"""

    release_date: str
    """模型发布日期（ISO 8601 格式，例如 `'2025-06-01'`）。"""

    last_updated: str
    """模型最后更新日期（ISO 8601 格式）。"""

    open_weights: bool
    """模型权重是否公开可用。"""

        # --- 输入约束 ---

    max_input_tokens: int
    """最大上下文窗口（token 数量）。"""

    text_inputs: bool
    """是否支持文本输入。"""

    image_inputs: bool
    """是否支持图像输入。"""
        # TODO: 补充关于格式的更多细节？

    image_url_inputs: bool
    """是否支持[图像 URL
输入](https://docs.langchain.com/oss/python/langchain/models#multimodal)。"""

    pdf_inputs: bool
    """是否支持[PDF 输入](https://docs.langchain.com/oss/python/langchain/models#multimodal)。"""
        # TODO: 补充关于格式的更多细节？例如 bytes 或 base64

    audio_inputs: bool
    """是否支持[音频输入](https://docs.langchain.com/oss/python/langchain/models#multimodal)。"""
        # TODO: 补充关于格式的更多细节？例如 bytes 或 base64

    video_inputs: bool
    """是否支持[视频输入](https://docs.langchain.com/oss/python/langchain/models#multimodal)。"""
        # TODO: 补充关于格式的更多细节？例如 bytes 或 base64

    image_tool_message: bool
    """是否可在 `ToolMessage` 内容中包含图像。"""

    pdf_tool_message: bool
    """是否可在 `ToolMessage` 内容中包含 PDF。"""

        # --- 输出约束 ---

    max_output_tokens: int
    """最大输出 token 数量。"""

    reasoning_output: bool
    """是否支持[推理 / 思维链](https://docs.langchain.com/oss/python/langchain/models#reasoning)。"""

    reasoning_effort_levels: list[str]
    """支持的推理努力级别（例如 `['low', 'medium', 'high']`）。

    Absent or empty if the model does not support a configurable reasoning
    effort. Only meaningful when `reasoning_output` is `True`.
    """

    reasoning_effort_default: str
    """提供商文档中记录的默认推理努力级别（如已知）。

    Absent when no default is documented. Only meaningful when
    `reasoning_effort_levels` is non-empty; not necessarily a member of
    `reasoning_effort_levels` itself (a model may default to unconfigurable
    behavior distinct from any explicit level).
    """

    text_outputs: bool
    """是否支持文本输出。"""

    image_outputs: bool
    """是否支持[图像输出](https://docs.langchain.com/oss/python/langchain/models#multimodal)。"""

    audio_outputs: bool
    """是否支持[音频输出](https://docs.langchain.com/oss/python/langchain/models#multimodal)。"""

    video_outputs: bool
    """是否支持[视频输出](https://docs.langchain.com/oss/python/langchain/models#multimodal)。"""

        # --- 工具调用 ---
    tool_calling: bool
    """是否支持[工具调用](https://docs.langchain.com/oss/python/langchain/models#tool-calling)。"""

    tool_choice: bool
    """是否支持[工具选择](https://docs.langchain.com/oss/python/langchain/models#forcing-tool-calls)。"""

    tool_call_streaming: bool
    """流式输出时，模型是否返回结构正确的 `tool_call_chunks`。

    仅在 `tool_calling` 为 `True` 时有意义。
    """

        # --- 对话过程中的变更 ---
    mid_conversation_system_messages: bool
    """在第一轮对话之后，是否发送位于当前位置的 `SystemMessage`。

    若缺失或为 `False`，则聊天模型可能会将其移至开头的系统提示中。
    """

    mid_conversation_tools: bool
    """是否可在对话过程中添加工具。

    工具通过消息添加，而非请求中的工具列表，因此其前的提示词前缀保持不变。隐含
    `mid_conversation_system_messages`。

    消息格式由提供方特定。每个设置此选项的提供方都接受工具的完整定义；部分还接受请求中已存在的工具引用，或可移除工具。
    """

        # --- 结构化输出 ---
    structured_output: bool
    """模型是否支持原生 [结构化输出](https://docs.langchain.com/oss/python/langchain/models#structured-outputs)。"""

        # --- 其他功能 ---

    attachment: bool
    """模型是否支持文件附件。"""

    temperature: bool
    """模型是否支持 temperature 参数。"""


ModelProfileRegistry = dict[str, ModelProfile]
"""Registry mapping model identifiers or names to their ModelProfile."""


def _warn_unknown_profile_keys(profile: ModelProfile) -> None:
    """如果 `profile` 包含未在 `ModelProfile` 中声明的键，则发出警告。

    Args:
        profile: 要检查未声明键的模型配置字典。
    """
    if not isinstance(profile, dict):
        return  # type: ignore[unreachable]

    try:
        declared = frozenset(get_type_hints(ModelProfile).keys())
    except (TypeError, NameError):
                # get_type_hints 在无法解析的正向引用上引发 NameError，且
                # 当注解计算为非类型对象时引发 TypeError。
        logger.debug(
            "Could not resolve type hints for ModelProfile; "
            "skipping unknown-key check.",
            exc_info=True,
        )
        return

    extra = sorted(set(profile) - declared)
    if extra:
        warnings.warn(
            f"Unrecognized keys in model profile: {extra}. "
            f"This may indicate a version mismatch between langchain-core "
            f"and your provider package. Consider upgrading langchain-core.",
            stacklevel=2,
        )
