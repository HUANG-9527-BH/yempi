"""模块包含与 `Runnable` 对象一起使用的类型定义。"""

from __future__ import annotations

from typing import TYPE_CHECKING, Any, Literal

from typing_extensions import NotRequired, TypedDict

if TYPE_CHECKING:
    from collections.abc import Sequence


class EventData(TypedDict, total=False):
    """与流式事件相关联的数据。"""

    input: Any
    """传递给生成该事件的 `Runnable` 的输入。

    输入有时在 `Runnable` 的 *START* 时可用，
    有时在 `Runnable` 的 *END* 时才可用。

    如果一个 `Runnable` 能够流式处理其输入，那么根据定义，它的输入直到 `Runnable`
    完成输入流式传输后才会被知晓。
    """
    error: NotRequired[BaseException]
    """在执行 `Runnable` 期间发生的错误。

    此字段仅在 `Runnable` 抛出异常时可用。

    !!! version-added "在 `langchain-core` 1.0.0 中新增"
    """
    output: Any
    """生成该事件的 `Runnable` 的输出。

    输出仅在 `Runnable` 的 *END* 时可用。

    For most `Runnable` objects, this field can be inferred from the `chunk` field,
    though there might be some exceptions for special a cased `Runnable` (e.g., like
    chat models), which may return more information.
    """
    chunk: Any
    """来自生成该事件的输出的流式块。

    块通常支持加法操作，将它们相加应得到生成该事件的 `Runnable` 的输出。
    """
    tool_call_id: NotRequired[str | None]
    """与工具执行相关的工具调用 ID。

    This field is available for the `on_tool_error` event and can be used to
    link errors to specific tool calls in stateless agent implementations.
    """


class BaseStreamEvent(TypedDict):
    """流式事件。

    由 `astream_events` 方法生成的流式事件的模式。

    Example:
        ```python
        from langchain_core.runnables import RunnableLambda


        async def reverse(s: str) -> str:
            return s[::-1]


        chain = RunnableLambda(func=reverse)

        events = [event async for event in chain.astream_events("hello")]

        # Will produce the following events
        # (where some fields have been omitted for brevity):
        [
            {
                "data": {"input": "hello"},
                "event": "on_chain_start",
                "metadata": {},
                "name": "reverse",
                "tags": [],
            },
            {
                "data": {"chunk": "olleh"},
                "event": "on_chain_stream",
                "metadata": {},
                "name": "reverse",
                "tags": [],
            },
            {
                "data": {"output": "olleh"},
                "event": "on_chain_end",
                "metadata": {},
                "name": "reverse",
                "tags": [],
            },
        ]
        ```
    """

    event: str
    """Event names are of the format: 事件名称格式为：`on_[runnable_type]_(start|stream|end)`。

    `Runnable` 类型包括：

    - **llm** - used by non chat models
    - **chat_model** - used by chat models
    - **prompt** --  e.g., `ChatPromptTemplate`
    - **tool** -- from tools defined via `@tool` decorator or inheriting
        from `Tool`/`BaseTool`
    - **chain** - most `Runnable` objects are of this type

    此外，事件按以下类别分类：

    - **start** - 当 `Runnable` 开始时
    - **stream** - 当 `Runnable` 流式传输时
    - **end** - 当 `Runnable` 结束时

    start、stream 和 end 与略有不同的 `data` 负载相关联。

    请参阅 `EventData` 的文档以获取更多详细信息。
    """
    run_id: str
    """用于跟踪给定 `Runnable` 执行的随机生成 ID。

    每个作为父级 `Runnable` 执行一部分而被调用的子 `Runnable` 都会分配一个唯一的 ID。
    """
    tags: NotRequired[list[str]]
    """与生成此事件的 `Runnable` 关联的标签。

    标签始终从父级 `Runnable` 对象继承。

    标签可以使用 `.with_config({"tags":  ["hello"]})` 绑定到 `Runnable`，
    或在运行时通过 `.astream_events(..., {"tags": ["hello"]})` 传入。
    """
    metadata: NotRequired[dict[str, Any]]
    """与生成此事件的 `Runnable` 关联的元数据。

    元数据可以使用

        `.with_config({"metadata": { "foo": "bar" }})`

    绑定到 `Runnable`， 或在运行时通过

        `.astream_events(..., {"metadata": {"foo": "bar"}})` 传入。
    """

    parent_ids: Sequence[str]
    """与该事件关联的父级 ID 列表。

    根事件将拥有空列表。

    For example, if a `Runnable` A calls `Runnable` B, then the event generated by
    `Runnable` B will have `Runnable` A's ID in the `parent_ids` field.

    父级 ID 的顺序从根父级到直接父级。

    仅在 v2 版本的 astream 事件 API 中受支持。v1 版本将返回空列表。
    """


class StandardStreamEvent(BaseStreamEvent):
    """遵循 LangChain 事件数据规范的标准流事件。"""

    data: EventData
    """事件数据。

    事件数据的内容取决于事件类型。
    """
    name: str
    """生成该事件的 `Runnable` 的名称。"""


class CustomStreamEvent(BaseStreamEvent):
    """用户自定义的流事件。"""

        # 重写事件字段以使其更具体。
    event: Literal["on_custom_event"]  # type: ignore[misc]
    """事件类型。"""
    name: str
    """事件的用户自定义名称。"""
    data: Any
    """与事件相关的数据。自由格式，可以是任意内容。"""


StreamEvent = StandardStreamEvent | CustomStreamEvent
